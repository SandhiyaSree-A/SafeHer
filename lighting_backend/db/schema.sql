-- Enable PostGIS extension if not exists
CREATE EXTENSION IF NOT EXISTS postgis;

-- 1. Table: sos_events
CREATE TABLE IF NOT EXISTS sos_events (
    id TEXT PRIMARY KEY,
    user_hash TEXT NOT NULL,
    geom GEOGRAPHY(Point,4326) NOT NULL,
    triggered_at TIMESTAMPTZ NOT NULL,
    is_false_alarm BOOLEAN DEFAULT FALSE
);

-- Index for spatial queries
CREATE INDEX IF NOT EXISTS sos_events_geom_idx ON sos_events USING GIST (geom);
-- Index for user deduplication lookups
CREATE INDEX IF NOT EXISTS sos_events_user_time_idx ON sos_events (user_hash, triggered_at);

-- 2. View: sos_hotspots
CREATE OR REPLACE VIEW sos_hotspots AS
WITH cells AS (
    SELECT 
        id,
        ST_AsText(ST_SnapToGrid(geom::geometry, 0.0014)) AS cid,
        user_hash,
        triggered_at,
        geom
    FROM sos_events
    WHERE NOT is_false_alarm
)
SELECT 
    cid,
    COUNT(*) AS alert_count,
    COUNT(DISTINCT user_hash) AS unique_users,
    MAX(triggered_at) AS last_alert_at,
    SUM(CASE WHEN EXTRACT(HOUR FROM triggered_at AT TIME ZONE 'UTC') >= 22 
               OR EXTRACT(HOUR FROM triggered_at AT TIME ZONE 'UTC') < 5 THEN 1 ELSE 0 END) AS night_count,
    -- Simple centroid of the snapped geometries
    ST_Centroid(ST_Collect(geom::geometry))::geography AS center
FROM cells
GROUP BY cid;

-- 3. Table: safest_routes (stores routes marked/ranked as safe upon reaching destination)
CREATE TABLE IF NOT EXISTS safest_routes (
    id TEXT PRIMARY KEY,
    journey_id TEXT,
    user_id TEXT,
    route_id TEXT,
    route_name TEXT,
    origin_lat DOUBLE PRECISION,
    origin_lng DOUBLE PRECISION,
    dest_lat DOUBLE PRECISION,
    dest_lng DOUBLE PRECISION,
    destination_address TEXT,
    transport_mode TEXT DEFAULT 'driving',
    composite_score DOUBLE PRECISION DEFAULT 0.0,
    risk_label TEXT,
    distance TEXT,
    duration TEXT,
    marked_safe_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS safest_routes_route_idx ON safest_routes (route_id);
CREATE INDEX IF NOT EXISTS safest_routes_user_idx ON safest_routes (user_id);

-- 4. Table: route_feedback (stores user feedback and unsafe reasons for routes)
CREATE TABLE IF NOT EXISTS route_feedback (
    id TEXT PRIMARY KEY,
    journey_id TEXT,
    user_id TEXT,
    route_id TEXT,
    route_name TEXT,
    origin_lat DOUBLE PRECISION,
    origin_lng DOUBLE PRECISION,
    dest_lat DOUBLE PRECISION,
    dest_lng DOUBLE PRECISION,
    destination_address TEXT,
    transport_mode TEXT DEFAULT 'driving',
    was_safe BOOLEAN DEFAULT FALSE,
    reasons TEXT, -- semicolon or comma separated reasons
    custom_reason TEXT,
    submitted_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS route_feedback_route_idx ON route_feedback (route_id);
CREATE INDEX IF NOT EXISTS route_feedback_user_idx ON route_feedback (user_id);

-- 5. Table: saved_offline_routes (stores frequent safe routes verified by repeated user feedback)
CREATE TABLE IF NOT EXISTS saved_offline_routes (
    id TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    route_id TEXT NOT NULL,
    route_name TEXT,
    origin_lat DOUBLE PRECISION,
    origin_lng DOUBLE PRECISION,
    dest_lat DOUBLE PRECISION,
    dest_lng DOUBLE PRECISION,
    destination_address TEXT,
    transport_mode TEXT DEFAULT 'driving',
    safe_rating_count INT DEFAULT 1,
    is_offline_ready BOOLEAN DEFAULT FALSE,
    composite_score DOUBLE PRECISION DEFAULT 0.0,
    risk_label TEXT,
    distance TEXT,
    duration TEXT,
    lighting_score DOUBLE PRECISION DEFAULT 0.0,
    crowd_density TEXT,
    traffic_condition TEXT,
    via_route TEXT,
    route_points_json TEXT, -- Full polyline points stored as JSON for offline display
    turn_steps_json TEXT,   -- Full turn-by-turn guidance steps stored as JSON
    first_rated_at TIMESTAMPTZ DEFAULT NOW(),
    last_rated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS saved_offline_routes_user_dest_idx ON saved_offline_routes (user_id, destination_address);
CREATE INDEX IF NOT EXISTS saved_offline_routes_coords_idx ON saved_offline_routes (dest_lat, dest_lng);

-- 6. Table: route_trust_scores (stores per-factor trust scores for every route analysis)
--    These historical scores are averaged and blended into future route scoring
--    for the same origin-destination corridor, improving accuracy over time.
CREATE TABLE IF NOT EXISTS route_trust_scores (
    id TEXT PRIMARY KEY,                          -- UUID generated by the client / server

    -- ── Identity ──────────────────────────────────────────────────────────────
    route_id              TEXT NOT NULL,          -- Route identifier (from OSRM / result)
    user_id               TEXT,                   -- Optional: null for anonymous requests
    session_id            TEXT,                   -- Optional journey/session ID

    -- ── Corridor (origin → destination) ───────────────────────────────────────
    origin_lat            DOUBLE PRECISION,
    origin_lng            DOUBLE PRECISION,
    dest_lat              DOUBLE PRECISION,
    dest_lng              DOUBLE PRECISION,
    destination_address   TEXT,
    transport_mode        TEXT DEFAULT 'driving',

    -- ── Per-factor scores (0–100 scale) ───────────────────────────────────────
    lighting_safety_score   DOUBLE PRECISION DEFAULT 0.0,   -- NASA nighttime light score
    average_light_score     DOUBLE PRECISION DEFAULT 0.0,   -- Mean light level along route
    traffic_score           DOUBLE PRECISION DEFAULT 0.0,   -- Traffic safety factor
    human_presence_score    DOUBLE PRECISION DEFAULT 0.0,   -- Human activity/foot traffic
    activity_density_score  DOUBLE PRECISION DEFAULT 0.0,   -- Area activity density
    pedestrian_score        DOUBLE PRECISION DEFAULT 0.0,   -- Pedestrian infrastructure
    sos_hotspot_score       DOUBLE PRECISION,               -- SOS incident proximity (NULL if unavailable)
    sos_hotspot_count       INT DEFAULT 0,                  -- Number of nearby SOS hotspots
    confidence              DOUBLE PRECISION DEFAULT 1.0,   -- Scoring confidence (0–1)

    -- ── Composite ─────────────────────────────────────────────────────────────
    composite_score         DOUBLE PRECISION DEFAULT 0.0,   -- Weighted final safety score
    risk_label              TEXT,                           -- LOW / MEDIUM / HIGH / UNKNOWN

    -- ── Route meta ────────────────────────────────────────────────────────────
    distance_km             DOUBLE PRECISION,
    duration_minutes        DOUBLE PRECISION,
    dark_points             INT DEFAULT 0,
    dark_stretches          INT DEFAULT 0,

    -- ── Timestamp ─────────────────────────────────────────────────────────────
    computed_at TIMESTAMPTZ DEFAULT NOW()
);

-- Fast lookup by route ID (most common query pattern)
CREATE INDEX IF NOT EXISTS rts_route_id_idx ON route_trust_scores (route_id);
-- Corridor-based historical average lookup
CREATE INDEX IF NOT EXISTS rts_corridor_idx  ON route_trust_scores (dest_lat, dest_lng);
-- User history
CREATE INDEX IF NOT EXISTS rts_user_idx      ON route_trust_scores (user_id);
-- Time-series analysis
CREATE INDEX IF NOT EXISTS rts_time_idx      ON route_trust_scores (computed_at);

